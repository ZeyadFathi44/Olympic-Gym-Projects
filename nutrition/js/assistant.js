function _claiLev(a,b){
  const m=a.length,n=b.length;
  const dp=Array.from({length:m+1},(_,i)=>Array.from({length:n+1},(_,j)=>i||j));
  for(let i=1;i<=m;i++)for(let j=1;j<=n;j++)
    dp[i][j]=a[i-1]===b[j-1]?dp[i-1][j-1]:1+Math.min(dp[i-1][j],dp[i][j-1],dp[i-1][j-1]);
  return dp[m][n];
}
function _claiNorm(s){
  return (s||'').toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g,'') // remove Arabic diacritics
    .replace(/ة/g,'ه').replace(/أ|إ|آ/g,'ا').replace(/ى/g,'ي')
    .replace(/[^\u0600-\u06FFa-z0-9\s]/g,' ')
    .replace(/\s+/g,' ').trim();
}
function _claiSim(a,b){
  const na=_claiNorm(a),nb=_claiNorm(b);
  if(na===nb)return 1;
  if(na.includes(nb)||nb.includes(na))return 0.9;
  const maxLen=Math.max(na.length,nb.length)||1;
  return 1-_claiLev(na,nb)/maxLen;
}
function _claiWordScore(input,keywords){
  const ni=_claiNorm(input);
  const words=ni.split(' ');
  if(!keywords||!keywords.length) return 0;
  const kwPhrases=keywords.map(k=>_claiNorm(k)).filter(p=>p&&p.length>1);
  const kwWords=[...new Set(kwPhrases.flatMap(p=>p.split(' ')).filter(x=>x.length>1))];
  let score=0;
  // Phrase-level: a full keyword phrase inside the question = strong specific signal.
  // Longer phrases score higher (more specific).
  for(const p of kwPhrases){
    if(ni.includes(p)) score += 3 + Math.min(2,(p.split(' ').length-1)*0.5);
  }
  // Word-level: each question word scores ONCE against its BEST keyword word —
  // so long keyword lists don't inflate scores on loose matches.
  for(const w of words){
    if(!w||w.length<2) continue;
    let best=0;
    for(const kww of kwWords){
      if(w===kww){ if(best<2) best=2; continue; }
      let cand=0;
      if(w.length>3&&kww.includes(w)) cand=1.5;
      else if(kww.length>3&&w.includes(kww)) cand=1.5;
      else {
        const sim=_claiSim(w,kww);
        if(sim>0.82) cand=sim*1.2;
      }
      if(cand>best) best=cand;
    }
    score+=best;
  }
  return score;
}

