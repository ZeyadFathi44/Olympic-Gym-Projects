// ─── BUILD PLAN CONTEXT FOR AI ──────────────────────────
function _claiGetPlanContext() {
  const g = id => document.getElementById(id)?.value || '';
  const lines = [];
  const name = g('c-name'); const nameAr = g('c-name-ar');
  if (name || nameAr) lines.push(`Client: ${name} (${nameAr})`);
  if (g('c-age')) lines.push(`Age: ${g('c-age')} | Gender: ${g('c-gender')} | Goal: ${g('c-goal')} | Phase: ${g('c-phase')}`);
  if (g('ib-weight')) lines.push(`Weight: ${g('ib-weight')}kg | Height: ${g('ib-height')}cm | BF%: ${g('ib-bf')}% | BMI: ${g('ib-bmi')}`);
  if (g('t-cal')) lines.push(`Daily Targets: ${g('t-cal')} kcal | P: ${g('t-prot')}g | C: ${g('t-carbs')}g | F: ${g('t-fats')}g | Water: ${g('t-water')}L`);
  const hCal = g('cc-H-cal'); const mCal = g('cc-M-cal'); const lCal = g('cc-L-cal');
  if (hCal || mCal || lCal) lines.push(`Carb Cycling — High: ${hCal||'—'} kcal | Med: ${mCal||'—'} kcal | Low: ${lCal||'—'} kcal`);
  if (g('c-injuries')) lines.push(`Health/Injuries: ${g('c-injuries')}`);
  if (g('c-allergies')) lines.push(`Allergies: ${g('c-allergies')}`);
  // Supplements
  const supps = [];
  document.querySelectorAll('#supp-rows .supp-row').forEach(r => {
    const inp = r.querySelectorAll('input');
    if (inp[0]?.value) supps.push(`${inp[0].value} ${inp[1]?.value} (${inp[2]?.value})`);
  });
  if (supps.length) lines.push(`Supplements: ${supps.join(', ')}`);
  return lines.length ? lines.join('\n') : null;
}

