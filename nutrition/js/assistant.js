function _wdFoodCats(name){
  const n=(name||'').toLowerCase();
  return Object.keys(FOOD_CAT_MAP).filter(cat=>
    FOOD_CAT_MAP[cat].some(w=>n.includes(w.toLowerCase()))
  );
}

function _wdCheckPanel(mealId,optN){
  const rows=[...document.querySelectorAll('#rows-'+mealId+'-'+optN+' .food-row')];
  const foods=rows.map(r=>r.dataset.foodName||'').filter(Boolean);
  if(foods.length<2)return[];
  const alerts=[];
  for(const cf of MEAL_CONFLICTS){
    const hasA=cf.a.some(w=>foods.some(f=>f.toLowerCase().includes(w.toLowerCase())));
    const hasB=cf.b.some(w=>foods.some(f=>f.toLowerCase().includes(w.toLowerCase())));
    if(hasA&&hasB)alerts.push({mealId,optN,foods,cf});
  }
  return alerts;
}

function claiCheckAllMeals(){
  if(typeof MEALS_DEF==='undefined')return[];
  const all=[];
  for(const m of MEALS_DEF)for(const o of OPTS_DEF){
    all.push(..._wdCheckPanel(m.id,o.n));
  }
  window._wdAlerts=all;
  _wdUpdateBanner(all);
  _wdUpdateBadge(all);
  return all;
}

function _wdUpdateBadge(alerts){
  const b=document.getElementById('clai-badge');
  if(!b)return;
  const has=alerts.filter(a=>a.cf.severity==='error').length;
  const hw=alerts.filter(a=>a.cf.severity==='warning').length;
  if(!alerts.length){b.style.display='none';return;}
  b.style.display='flex';
  b.textContent=alerts.length;
  b.style.background=has?'#ef4444':hw?'#f97316':'#3b82f6';
}

function _wdUpdateBanner(alerts){
  const el=document.getElementById('clai-wd-status');
  if(!el)return;
  const e=alerts.filter(a=>a.cf.severity==='error').length;
  const w=alerts.filter(a=>a.cf.severity==='warning').length;
  if(!alerts.length){el.textContent='✅ لا توجد تعارضات — وجباتك سليمة';el.style.color='#4ade80';}
  else if(e){el.textContent=`🚨 ${e} تعارض خطير + ${w} تحذير — اضغط "تحليل الآن"`;el.style.color='#ef4444';}
  else{el.textContent=`⚠️ ${alerts.length} ملاحظة على مكونات الوجبات`;el.style.color='#f97316';}
}

