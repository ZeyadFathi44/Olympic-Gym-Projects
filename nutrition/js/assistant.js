// ── LIVE PLAN MATH — answers numeric questions with the coach's real plan data.
// Runs when the KB doesn't match; returns a reply string or null.
function claiPlanAnswer(input) {
  const isAr = _claiIsAr(input);
  const ni = _claiNorm(input);
  const Q = re => re.test(ni);
  const g = id => parseFloat(document.getElementById(id)?.value) || 0;
  const gs = id => (document.getElementById(id)?.value || '').trim();
  const num = x => Math.round(x).toLocaleString('en-US');
  const dec = (x, d = 1) => (Math.round(x * Math.pow(10, d)) / Math.pow(10, d)).toFixed(d);
  const client = gs('c-name') || gs('c-name-ar');

  const weight = g('ib-weight'), height = g('ib-height');
  const age = g('c-age') || g('ib-age');
  const genderStr = gs('c-gender') || gs('ib-gender');
  const isFemale = /femal|أنثى|بنت|انثى|حرم/i.test(genderStr);

  // ── calories / TDEE / BMR ──
  if (Q(/calori|tdee|bmr|kcal|سعرات|كالوري|سعرة|tdee|احتياج يومي|كام سعرة/)) {
    const tCal = g('t-cal'), tProt = g('t-prot'), tCarb = g('t-carbs'), tFat = g('t-fats');
    let tdee = (typeof ccGetTDEE === 'function') ? ccGetTDEE() : 0;
    let calcNote = '';
    if (!tdee && weight && height && age) {
      const bmr = Math.round(10 * weight + 6.25 * height - 5 * age + (isFemale ? -161 : 5));
      tdee = Math.round(bmr * 1.5);          // app default activity factor
      calcNote = isAr
        ? `\n\n(حسبناها من وزنكم ${num(weight)} كجم — Mifflin-St Jeor × 1.5، عدّلها بحسب نشاطكم الفعلي)`
        : `\n\n(Calculated from weight ${num(weight)}kg — Mifflin-St Jeor × 1.5; adjust to real activity)`;
    }
    if (!tCal && !tdee) return null;         // nothing to compute from
    const L = [];
    if (isAr) {
      L.push('🔬 **أرقام الخطة الحالية:**');
      if (tCal) L.push(`• الهدف اليومي: **${num(tCal)} kcal**` + (tProt ? ` — بروتين ${num(tProt)}ج / كارب ${num(tCarb)}ج / دهون ${num(tFat)}ج` : ''));
      if (tdee) L.push(`• TDEE (الثبات): **${num(tdee)} kcal**`);
      if (tdee) L.push(`• عجز آمن للتنشيف: TDEE − 400 إلى − 600 = **${num(tdee-600)}–${num(tdee-400)} kcal**`);
      if (tdee) L.push(`• فائض للتضخيم النظيف: TDEE + 250 = **${num(tdee+250)} kcal**`);
      L.push(calcNote);
      if (client) L.push(`\u200b(ده لعميل: ${client})`);
      L.push('💡 خلي العجز تحت أقل من 25% من TDEE من غير شدة أسبوعية عالية — وقّي المطبوع بالنقص في الأداء. عدّل وأنا أحسبلك تاني.');
    } else {
      L.push('🔬 **Current plan numbers:**');
      if (tCal) L.push(`• Daily target: **${num(tCal)} kcal**` + (tProt ? ` — P${num(tProt)}g / C${num(tCarb)}g / F${num(tFat)}g` : ''));
      if (tdee) L.push(`• TDEE (maintenance): **${num(tdee)} kcal**`);
      if (tdee) L.push(`• Safe cutting deficit: TDEE − 400 to − 600 = **${num(tdee-600)}–${num(tdee-400)} kcal**`);
      if (tdee) L.push(`• Clean bulk surplus: TDEE + 250 = **${num(tdee+250)} kcal**`);
      L.push(calcNote);
      L.push('💡 Keep the deficit under ~25% of TDEE unless performance drops are acceptable. Update the plan and ask me again!');
    }
    return L.join('\n');
  }

  // ── protein need ──
  if (Q(/how much protein|protein need|protein per day|protein intake|احتياج بروتين|بروتين يومي|كم بروتين نقطة/) && (weight || g('t-prot'))) {
    const tProt = g('t-prot');
    const L = [];
    if (isAr) {
      if (tProt) L.push(`🎯 هدف البروتين في خطة عميلك دلوقتي: **${num(tProt)} جم/يوم**` + (weight ? ` (≈ ${dec(tProt / weight, 2)} جم/كجم على وزن ${num(weight)})` : ''));
      if (weight) L.push(`📐 المعدل الآمن: **1.6–2.2 جم/كجم** → يعني ${num(weight*1.6)}–${num(weight*2.2)} جم ليكم.\nقسّمها على 4 وجبات (خلال ~0.4 جم/كجم للوجبة للاستفادة القصوى).`);
    } else {
      if (tProt) L.push(`🎯 Current plan protein target: **${num(tProt)} g/day**` + (weight ? ` (≈ ${dec(tProt / weight, 2)} g/kg at ${num(weight)}kg)` : ''));
      if (weight) L.push(`📐 Evidence range: **1.6–2.2 g/kg** → ${num(weight*1.6)}–${num(weight*2.2)} g for you.\nSplit across 4 meals (~0.4 g/kg per meal maximizes synthesis).`);
    }
    if (!L.length) return null;
    return L.join('\n') + (isAr ? '\n\nولو محتاج أكل بدل المكملات: بيض/تونة/جبنة قريش/فراخ/سمك — أكل بسيط وأرخص من المكملات.' : '\n\nBudget-friendly sources: eggs, tuna, low-fat curd cheese, poultry, fish — real food beats powders.');
  }

  // ── water ──
  if (Q(/\bwater\b|مياه|ماء|ميه|ميى/)) {
    const tw = g('t-water');
    const L = [];
    if (tw) {
      if (isAr) L.push(`💧 هدف المياه في الخطة: **${tw} لتر/يوم**`);
      else L.push(`💧 Current plan water target: **${tw} L/day**`);
    }
    if (weight) {
      if (isAr) L.push(`📝 الحسبة الأساسية: وزن × 33–40 مل → **${dec(weight*33/1000,1)}–${dec(weight*40/1000,1)} لتر** + 0.5–1 لتر إضافي في أيام التمرين العنيف أو الحر.`);
      else L.push(`📝 Rule of thumb: bodyweight × 33–40 ml → **${dec(weight*33/1000,1)}–${dec(weight*40/1000,1)} L**, plus **0.5–1 L** extra on intense training or hot days.`);
    } else {
      L.push(isAr ? '📝 المعدل العام: 2.5–3.5 لتر للراجل، 2–3 للست، زوّد بالتمرين.' : '📝 General: 2.5–3.5 L for men, 2–3 L for women, more on training days.');
    }
    L.push(isAr ? '⚡ علامات نقص: بول غامق، وحش في الـ pump، تقلصات. الإلكتروليتات (صوديوم/بوتاسيوم/ماجنيسيوم) أهم من كمية المياه نفسها.' : '⚡ Deficiency signs: dark urine, weak pumps, cramps. Electrolytes (Na/K/Mg) matter as much as volume.');
    return L.join('\n');
  }

  // ── deficit / cutting / carb cycling math ──
  if (Q(/عجز|ديفيسيت|deficit|cutting|cutting plan|carb cycling|كارب سايكلينج|كارب سايكلينغ/)) {
    const ch = (typeof ccGetTierValues === 'function');
    const H = ch ? ccGetTierValues('H') : null, Mrow = ch ? ccGetTierValues('M') : null, Lrow = ch ? ccGetTierValues('L') : null;
    const tdee = (typeof ccGetTDEE === 'function') ? ccGetTDEE() : 0;
    if (ch && tdee && (H || Mrow || Lrow) && window._ccWeek) {
      const week = window._ccWeek;
      const n = t => week.filter(x => x === t).length;
      const calOf = v => ccTierCal ? ccTierCal(v) : (v.cal || 0);
      const dH = (H && calOf(H)) ? calOf(H) - tdee : 0;
      const dM = (Mrow && calOf(Mrow)) ? calOf(Mrow) - tdee : 0;
      const dL = (Lrow && calOf(Lrow)) ? calOf(Lrow) - tdee : 0;
      const net = dH*n('H') + dM*n('M') + dL*n('L');
      const kg = Math.abs(net) / 7700;
      const L = [];
      if (isAr) {
        L.push(`🧮 **كارب سايكلينج اللي مكتوب دلوقتي:**`);
        L.push(`🔥 عالي: ${n('H')} أيام × ${num(H ? calOf(H) : 0)} kcal (${dH>=0?'+':''}${num(dH)} مقابل TDEE)`);
        L.push(`⚖️ متوسط: ${n('M')} أيام × ${num(Mrow ? calOf(Mrow) : 0)} kcal (${dM>=0?'+':''}${num(dM)})`);
        L.push(`🧊 قليل: ${n('L')} أيام × ${num(Lrow ? calOf(Lrow) : 0)} kcal (${dL>=0?'+':''}${num(dL)})`);
        L.push(`⚖️ صافي الأسبوع: **${net>=0?'+':'−'}${num(Math.abs(net))} kcal** ≈ ${kg.toFixed(2)} كجم ${net<0?'فقدان':'زيادة'} دهن/أسبوع على TDEE ${num(tdee)}.`);
        if (net >= 0) L.push('⚠️ ده مش عجز — لو الهدف تنشيف، نزّل كارب أيام قليلة أو زوّد يوم Low.');
      } else {
        L.push(`🧮 **Your current carb-cycling setup:**`);
        L.push(` High: ${n('H')} days × ${num(H?calOf(H):0)} kcal (${dH>=0?'+':''}${num(dH)} vs TDEE)`);
        L.push(` Med: ${n('M')} × ${num(Mrow?calOf(Mrow):0)} kcal (${dM>=0?'+':''}${num(dM)})`);
        L.push(` Low: ${n('L')} × ${num(Lrow?calOf(Lrow):0)} kcal (${dL>=0?'+':''}${num(dL)})`);
        L.push(`⚖️ Weekly net: **${net>=0?'+':'−'}${num(Math.abs(net))} kcal** ≈ ${kg.toFixed(2)} kg ${net<0?'fat loss':'fat gain'}/week on TDEE ${num(tdee)}.`);
        if (net >= 0) L.push('⚠️ That is NOT a deficit — for cutting, drop the Low-day carbs or add another Low day.');
      }
      return L.join('\n');
    }
    // no data → generic guidance
    return isAr
      ? `📉 **القاعدة الذهبية للعجز:**\n1. حسب TDEE من الـ InBody أو المولد الماكرو (0.5–1%)\n2. عجز من **15–25%** من TDEE (يعني ~350–600 كالوري)\n3. بروتين مرتفع ثابت: 2–2.3 جم/كجم\n4. الدهون أقل من 0.8 جم/كجم — الباقي كارب\n5. الاستمرار أسبوعين قبل أي تحكيم\n\nلو حلّيت بيانات العميل في الخطة، اسألني تاني حسبلك كل حاجة تشتغل مع بعضها.`
      : `📉 **The golden deficit rules:**\n1. Estimate TDEE from InBody data or the macro generator\n2. Cut **15–25%** of TDEE (~350–600 kcal)\n3. Keep protein high & constant: 2–2.3 g/kg\n4. Fats floor at 0.8 g/kg, carbs take the rest\n5. Stay 2 weeks before judging\n\nOnce the client data is in the plan, ask again and I'll compute the exact numbers.`;
  }

  return null;
}

function claiGetResponse(input) {
  const isAr = _claiIsAr(input);
  let best = null, bestScore = 0;

  for (const entry of CLAI_KB) {
    const score = _claiWordScore(input, entry.kw);
    if (score > bestScore) { bestScore = score; best = entry; }
  }

  // Secondary pass — fuzzy whole-question vs keyword phrases (typos, long phrasings)
  if (bestScore < 0.4) {
    for (const entry of CLAI_KB) {
      for (const kw of entry.kw) {
        if (kw.length >= 4) {
          const s = _claiSim(input, kw);
          if (s > 0.82) {
            const sc = 0.4 + s * 0.4;
            if (sc > bestScore) { bestScore = sc; best = entry; }
          }
        }
      }
    }
  }

  // threshold: if nothing matches well enough → try live plan math, then suggest topics
  if (bestScore < 0.4) {
    const planAns = (typeof claiPlanAnswer === 'function') ? claiPlanAnswer(input) : null;
    if (planAns) return planAns;
    const pairs = [
      {
        ar: `🤔 لم أفهم سؤالك تماماً! جرّب إعادة الصياغة أو اسألني عن:\n• البروتين والمكملات\n• حرق الدهون وبناء العضلات\n• الوجبات والأطعمة\n• التوقيت والتعافي`,
        en: `🤔 I didn't fully get that! Try rephrasing, or ask me about:\n• Protein & supplements\n• Fat loss & muscle building\n• Meals & foods\n• Timing & recovery`
      },
      {
        ar: `💭 سؤالك خارج نطاق تخصصي أو لم أفهمه جيداً. أنا متخصص في التغذية الرياضية — اسألني بشكل آخر! مثلاً: "كم بروتين أحتاج يومياً؟" أو "ما أفضل وجبة بعد التمرين؟"`,
        en: `💭 That's outside my zone or unclear. I'm a sports-nutrition specialist — try another angle, e.g. "how much protein per day?" or "best post-workout meal?"`
      },
      {
        ar: `🏋️ لم أجد إجابة دقيقة لهذا في قاعدة بياناتي. المواضيع المتاح عندها معرفة قوية: الماكرو (كالوري/بروتين/كارب/دهون)، الكرياتين والواي، الكارديو والكيتو، رمضان، الترطيب، النوم، الصيام، ثبات الوزن، فيتامينات ونواقص، سكري وضغط وهشاشة وتكيس... اسأل عن أي واحدة!`,
        en: `🏋️ No precise answer for that in my database. Strong topics: macros (cal/protein/carb/fat), creatine & whey, cardio & keto, Ramadan, hydration, sleep, fasting, plateaus, vitamins & deficiencies, diabetes / blood pressure / osteoporosis / PCOS... ask about any!`
      },
    ];
    const p = pairs[_claiTurn % pairs.length];
    return isAr ? p.ar : p.en;
  }

  // pick answer matching the asker's language (aen = English answers)
  const pool = (!isAr && Array.isArray(best.aen) && best.aen.length) ? best.aen : best.ans;
  const ans = pool[Math.floor(Math.random() * pool.length)];
  return ans.trim();
}

